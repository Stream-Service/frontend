document.addEventListener('DOMContentLoaded', () => {
    // UI Elements
    const emailSection = document.getElementById('emailSection');
    const otpSection = document.getElementById('otpSection');
    const emailInput = document.getElementById('email');
    const otpInput = document.getElementById('otp');
    const sendOtpBtn = document.getElementById('sendOtpBtn');
    const verifyOtpBtn = document.getElementById('verifyOtpBtn');
    const resetPasswordBtn = document.getElementById('resetPasswordBtn');
    const resetSection = document.getElementById('resetSection');
    const messageBox = document.getElementById('messageDisplay');

    // --- DYNAMIC URL LOGIC ---bb
    // 1. Get Base from window.CONFIG (generated by Node.js) or fallback to /api/auth
     
    
    // 2. Build the Endpoint. 
    // IMPORTANT: If BASE_URL is "/api/auth", this becomes "/api/auth/users/auth"
    const AUTH_ENDPOINT = `${post}/auth/users`;
    
    console.log("🛠️ Current Auth Endpoint:", AUTH_ENDPOINT);

    // --- STEP 1: SEND OTP ---
    sendOtpBtn.addEventListener('click', async () => {
        const email = emailInput.value.trim();
        if (!email) return showMessage("Please enter an email.", "error");

        setLoading(sendOtpBtn, true, "Sending...");

        const targetUrl = `${AUTH_ENDPOINT}/forgot_password`;
        console.log("📡 Fetching:", targetUrl);

        try {
            const response = await fetch(targetUrl, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ email: email })
            });

            const data = await response.json();

            if (response.ok) {
                showMessage("OTP sent! Please check your email.", "success");
                emailSection.style.display = "none";
                otpSection.style.display = "block";
            } else {
                // If 500 error, 'data' might contain the Python traceback if you enabled it
                showMessage(data.message || data.detail || "Server Error (500)", "error");
                console.error("❌ Server Response:", data);
            }
        } catch (err) {
            console.error("🌐 Network Error:", err);
            showMessage("Network error. Check if backend is running.", "error");
        } finally {
            setLoading(sendOtpBtn, false, "Send OTP");
        }
    });

    // --- STEP 2: VERIFY OTP ---
    verifyOtpBtn.addEventListener('click', async () => {
        const otp = otpInput.value.trim();
        const email = emailInput.value.trim();

        if (!otp) return showMessage("Please enter the OTP.", "error");

        setLoading(verifyOtpBtn, true, "Verifying...");

        const targetUrl = `${AUTH_ENDPOINT}/forgot/verify-otp`;
        console.log("📡 Fetching:", targetUrl);

        try {
            const response = await fetch(targetUrl, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ email: email, otp: otp })
            });

            const data = await response.json();

            if (response.ok) {
                showMessage("OTP verified! Now set your new password.", "success");
                otpSection.style.display = "none";
                resetSection.style.display = "block";
            } else {
                showMessage(data.message || data.detail || "Invalid OTP.", "error");
            }
        } catch (err) {
            showMessage("Network error. Try again.", "error");
        } finally {
            setLoading(verifyOtpBtn, false, "Verify OTP");
        }
    });

    // --- STEP 3: RESET PASSWORD ---
    const newPasswordInput = document.getElementById('newPassword');
    const confirmPasswordInput = document.getElementById('confirmPassword');

    resetPasswordBtn.addEventListener('click', async () => {
        const newPassword = newPasswordInput.value.trim();
        const confirmPassword = confirmPasswordInput.value.trim();
        const email = emailInput.value.trim();
        const otp = otpInput.value.trim();

        if (!newPassword) return showMessage("Please enter a new password.", "error");
        if (newPassword !== confirmPassword) return showMessage("Passwords do not match.", "error");

        setLoading(resetPasswordBtn, true, "Resetting...");

        const targetUrl = `${AUTH_ENDPOINT}/forgot/reset-password`;
        console.log("📡 Fetching:", targetUrl);

        try {
            const response = await fetch(targetUrl, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ email: email, otp: otp, new_password: newPassword })
            });

            const data = await response.json();

            if (response.ok) {
                showMessage("Password reset successful! Redirecting to login...", "success");
                setTimeout(() => {
                    window.location.href = "/templates/login.html";
                }, 2000);
            } else {
                showMessage(data.message || data.detail || "Failed to reset password.", "error");
            }
        } catch (err) {
            showMessage("Network error. Try again.", "error");
        } finally {
            setLoading(resetPasswordBtn, false, "Reset Password");
        }
    });

    // Helpers
    function showMessage(msg, type) {
        messageBox.textContent = msg;
        messageBox.style.color = type === "success" ? "#2ecc71" : "#e74c3c";
    }

    function setLoading(btn, isLoading, text) {
        btn.disabled = isLoading;
        btn.textContent = text;
    }
});